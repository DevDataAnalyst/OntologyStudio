"""
Extract bundle I/O (WS1). A bundle is what the extractor captured from SAP BusinessObjects:

    manifest.json        source system, extraction methods, counts
    universe.json        data foundation (tables, joins, contexts) + business layer (items, prompts, hierarchies,
                         security profiles)
    mapping.json         BO physical table -> Unity Catalog table (filled in by the user for a client Universe)
    reports/<id>.json    Webi document: data providers (query spec + query plan SQL), variables, blocks

It is read from a folder, a .zip (upload or UC Volume) or built in memory (the synthetic fixture).
The format is documented in docs/sapbo/extract-bundle.md.
"""
from __future__ import annotations

import io
import json
import pathlib
import zipfile

REQUIRED = ("manifest", "universe")


class BundleError(ValueError):
    pass


def _check(b: dict) -> dict:
    missing = [k for k in REQUIRED if not b.get(k)]
    if missing:
        raise BundleError(f"the bundle has no {', '.join(missing)}.json")
    b.setdefault("reports", [])
    b.setdefault("mapping", {"tables": []})
    u = b["universe"]
    for key in ("dataFoundation", "businessLayer"):
        u.setdefault(key, {})
    return b


def load_dir(path: str | pathlib.Path) -> dict:
    d = pathlib.Path(path)
    b = {}
    for key in ("manifest", "universe", "mapping"):
        f = d / f"{key}.json"
        if f.exists():
            b[key] = json.loads(f.read_text(encoding="utf-8"))
    b["reports"] = [json.loads(p.read_text(encoding="utf-8")) for p in sorted((d / "reports").glob("*.json"))]
    return _check(b)


def load_zip(data: bytes) -> dict:
    b, reports = {}, []
    with zipfile.ZipFile(io.BytesIO(data)) as z:
        for name in z.namelist():
            if not name.endswith(".json"):
                continue
            parts = name.replace("\\", "/").split("/")
            doc = json.loads(z.read(name).decode("utf-8-sig"))
            if len(parts) >= 2 and parts[-2] == "reports":
                reports.append(doc)
            elif parts[-1][:-5] in ("manifest", "universe", "mapping"):
                b[parts[-1][:-5]] = doc
    b["reports"] = sorted(reports, key=lambda r: str(r.get("id")))
    return _check(b)


def to_zip(b: dict) -> bytes:
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for key in ("manifest", "universe", "mapping"):
            if key in b:
                z.writestr(f"{key}.json", json.dumps(b[key], indent=2))
        for r in b.get("reports", []):
            z.writestr(f"reports/{r['id']}.json", json.dumps(r, indent=2))
    return buf.getvalue()


def load(path_or_bytes) -> dict:
    if isinstance(path_or_bytes, (bytes, bytearray)):
        return load_zip(bytes(path_or_bytes))
    p = pathlib.Path(path_or_bytes)
    return load_dir(p) if p.is_dir() else load_zip(p.read_bytes())


def sample() -> dict:
    """The synthetic CNR Finance bundle (samples/sapbo/cnr_finance, regenerated by modules.sapbo.fixture)."""
    p = pathlib.Path(__file__).resolve().parents[2] / "samples" / "sapbo" / "cnr_finance"
    if p.exists():
        return load_dir(p)
    from . import fixture
    return _check(fixture.build())


def inventory(b: dict) -> dict:
    u = b["universe"]
    df, bl = u.get("dataFoundation", {}), u.get("businessLayer", {})
    items = bl.get("items", [])
    return {
        "universe": u.get("name"), "tables": len(df.get("tables", [])), "joins": len(df.get("joins", [])),
        "contexts": len(df.get("contexts", [])),
        "dimensions": sum(i.get("type") in ("Dimension", "Attribute") for i in items),
        "measures": sum(i.get("type") == "Measure" for i in items),
        "filters": sum(i.get("type") == "Filter" for i in items),
        "prompts": len(bl.get("parameters", [])), "hierarchies": len(bl.get("hierarchies", [])),
        "reports": len(b.get("reports", [])),
        "sql_statements": sum(len(dp.get("queryPlan", {}).get("statements", []))
                              for r in b.get("reports", []) for dp in r.get("dataProviders", [])),
        "variables": sum(len(r.get("variables", [])) for r in b.get("reports", [])),
    }
