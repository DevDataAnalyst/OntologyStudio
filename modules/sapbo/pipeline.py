"""
End-to-end run of the SAP BO POC pipeline, up to the generated metric views and Power BI helpers.

    result = run(bundle_dict)                  # deterministic stages only
    enrich.propose(result["concepts"], chat)   # optional WS3, then review in the app
    rebuild(result)                            # re-generate Ossie / metric views after reviews

Everything returned is JSON-able except nothing (dicts, lists, strings), so it can sit in st.session_state or be
written to a run folder (write_run).
"""
from __future__ import annotations

import json
import pathlib

from . import consume, gaps, normalize, parse, recon, to_mv, to_ossie


def run(b: dict, catalog: str = "cnfinance", schema: str = "semantic", report_metrics: bool = True) -> dict:
    sir = parse.to_sir(b)
    concepts = normalize.run(sir)
    rows = gaps.required_artifacts(sir)
    result = {"sir": sir, "concepts": concepts, "required": rows, "coverage": gaps.extraction_coverage(rows),
              "catalog": catalog, "schema": schema, "report_metrics": report_metrics}
    return rebuild(result)


def rebuild(result: dict) -> dict:
    """Regenerate everything downstream of the concepts (after enrichment or review)."""
    sir, c = result["sir"], result["concepts"]
    result["gap_report"] = gaps.gap_report_md(sir, c, result["coverage"])
    result["provenance"] = gaps.provenance_summary(c)
    doc = to_ossie.build(c)
    result["ossie"] = doc
    result["ossie_yaml"] = to_ossie.to_yaml(doc)
    rep = to_ossie.validate(doc)
    result["ossie_validation"] = {"ok": rep.ok, "headline": rep.headline(),
                                  "findings": [{"severity": f.severity, "check": f.check, "message": f.message}
                                               for f in rep.findings]}
    mv = to_mv.convert(doc, result["catalog"], result["schema"], result["report_metrics"])
    result["mv"] = mv
    result["conversion_report"] = to_mv.report_md(mv)
    specs = consume.block_specs(sir, c, mv)
    result["blocks"] = specs
    result["p2_views"] = consume.p2_views(specs, result["catalog"], result["schema"])
    result["dax"] = consume.dax_measures(mv)
    governed = {m["name"]: m["label"] for m in c["metrics"].values() if m["scope"] == "universe"}
    result["pattern3"] = [consume.classify_dax(s["name"], s["dax"], governed) | {"dax": s["dax"],
                                                                                "expected": s["kind_expected"]}
                          for s in consume.PATTERN3_SAMPLES]
    result["recon_plan"] = recon.plan(sir, c, mv)
    return result


def deploy_sql(result: dict, include_p2: bool = True) -> str:
    """One script for the manual deployment: schema, metric views, Pattern 2 views."""
    cat, sch = result["catalog"], result["schema"]
    parts = [f"-- Generated by Ontology Studio from SAP BO Universe '{result['sir']['universe']['name']}'.",
             "-- Run it by hand in a SQL editor (the POC keeps deployment manual).",
             f"CREATE SCHEMA IF NOT EXISTS {cat}.{sch};"]
    parts += [d + ";" for d in result["mv"]["ddl"].values()]
    if include_p2:
        parts += ["-- Pattern 2: plain SQL views over the metric views (one per report block)"]
        parts += [v["ddl"] + ";" for v in result["p2_views"]]
    return "\n\n".join(parts) + "\n"


def write_run(result: dict, folder: str | pathlib.Path) -> pathlib.Path:
    d = pathlib.Path(folder)
    (d / "metric_views").mkdir(parents=True, exist_ok=True)
    (d / "sir.json").write_text(json.dumps(result["sir"], indent=2, default=str), encoding="utf-8")
    (d / "concepts.json").write_text(json.dumps(result["concepts"], indent=2, default=str), encoding="utf-8")
    (d / "gap_report.md").write_text(result["gap_report"], encoding="utf-8")
    (d / "model.ossie.yaml").write_text(result["ossie_yaml"], encoding="utf-8")
    (d / "conversion_report.md").write_text(result["conversion_report"], encoding="utf-8")
    from modules import metric_views as mvlib
    for n, v in result["mv"]["views"].items():
        (d / "metric_views" / f"{n}.yaml").write_text(mvlib.to_yaml(v), encoding="utf-8")
    (d / "deploy.sql").write_text(deploy_sql(result), encoding="utf-8")
    (d / "recon.sql").write_text("\n\n".join(f"-- {i['report']}/{i['data_provider']} ({i['status']})\n"
                                             + (i["compare_sql"] or f"-- {i['reason']}") + ";"
                                             for i in result["recon_plan"]), encoding="utf-8")
    (d / "powerbi_measures.tmdl").write_text(consume.tmdl_measures(result["dax"]), encoding="utf-8")
    return d
